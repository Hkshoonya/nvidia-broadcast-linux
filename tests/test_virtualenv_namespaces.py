"""Exercise namespace startup in real Python processes, without host changes."""

import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from unittest import mock
import venv

from scripts import install_runtime_variant as installer


class VirtualenvNamespaceTests(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory(prefix="nvb namespace ")
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name)
        self.venv = self.root / "venv"
        venv.EnvBuilder(with_pip=False).create(self.venv)
        self.python = self.venv / ("Scripts/python.exe" if os.name == "nt" else "bin/python")
        self.site = Path(self.run_python(
            "import sysconfig; print(sysconfig.get_path('purelib'))"
        ).stdout.strip())
        self.system_site = self.root / "distro site"
        self.system_site.mkdir()

    def run_python(self, code):
        return subprocess.run(
            [str(self.python), "-I", "-c", code],
            capture_output=True, text=True, timeout=15,
        )

    def configure(self):
        with (
            mock.patch.object(installer.sys, "prefix", str(self.venv)),
            mock.patch.object(installer.sysconfig, "get_path", return_value=str(self.site)),
        ):
            installer.prepare_virtualenv_namespaces()

    def distro_namespace(self):
        # The legacy namespace .pth generated by setuptools, as shipped in
        # Fedora 44's python3-protobuf 3.19.6-20.fc44 RPM. It deliberately
        # searches only its own site, even when a venv contains google too.
        (self.system_site / "protobuf-3.19.6-nspkg.pth").write_text(
            "import sys, types, os;"
            "p = os.path.join(sys._getframe(1).f_locals['sitedir'], *('google',));"
            "importlib = __import__('importlib.util');"
            "__import__('importlib.machinery');"
            "m = sys.modules.setdefault('google', importlib.util.module_from_spec("
            "importlib.machinery.PathFinder.find_spec('google', [os.path.dirname(p)])));"
            "m = m or sys.modules.setdefault('google', types.ModuleType('google'));"
            "mp = (m or []) and m.__dict__.setdefault('__path__',[]);"
            "(p not in mp) and mp.append(p)\n"
        )

    def test_venv_protobuf_wins_over_legacy_distro_namespace(self):
        for site, version in ((self.site, "6.33.6"), (self.system_site, "3.19.6")):
            package = site / "google/protobuf"
            package.mkdir(parents=True)
            (package / "__init__.py").write_text(f"__version__ = {version!r}\n")
        (self.site / "google/protobuf/runtime_version.py").write_text("MAJOR = 6\n")
        (self.system_site / "google/distro_only.py").write_text("VALUE = 42\n")
        self.distro_namespace()
        # Process the synthetic distro site after every normal venv site.
        # Fedora can expose both lib64 and lib paths to the same venv site;
        # putting this in a venv .pth would incorrectly run it twice.
        program = (
            f"import site; site.addsitedir({str(self.system_site)!r}); "
            "import json, google.protobuf; "
            "from google.protobuf import runtime_version; "
            "from google import distro_only; "
            "print(json.dumps([google.protobuf.__version__, "
            "google.protobuf.__file__, runtime_version.MAJOR, distro_only.VALUE]))"
        )
        broken = self.run_python(program)
        self.assertNotEqual(broken.returncode, 0)
        self.assertIn("cannot import name 'runtime_version'", broken.stderr)
        self.assertIn(str(self.system_site), broken.stderr)

        self.configure()
        self.configure()  # Ordinary reinstalls leave the same startup behavior.
        fixed = self.run_python(program)
        self.assertEqual(fixed.returncode, 0, fixed.stderr)
        self.assertEqual(fixed.stderr, "")
        version, origin, major, other = json.loads(fixed.stdout)
        self.assertEqual(version, "6.33.6")
        self.assertTrue(Path(origin).resolve().is_relative_to(self.site.resolve()))
        self.assertEqual((major, other), (6, 42))

    def test_fresh_venv_without_google_has_no_startup_error(self):
        self.configure()
        result = self.run_python("print('ready')")
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(result.stdout, "ready\n")
        self.assertEqual(result.stderr, "")

    def test_regular_google_package_remains_usable(self):
        package = self.site / "google"
        package.mkdir()
        (package / "__init__.py").write_text("VALUE = 17\n")
        self.configure()
        result = self.run_python("import google; print(google.VALUE)")
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(result.stdout, "17\n")
        self.assertEqual(result.stderr, "")

    def test_existing_hook_symlink_is_replaced_without_changing_its_target(self):
        outside = self.root / "outside.py"
        outside.write_text("unchanged\n")
        hook = self.site / "00-nvbroadcast-google-namespace.pth"
        hook.symlink_to(outside)
        self.configure()
        self.assertEqual(outside.read_text(), "unchanged\n")
        self.assertFalse(hook.is_symlink())
        self.assertEqual(hook.stat().st_mode & 0o777, 0o644)
        result = self.run_python("print('ready')")
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(result.stderr, "")

    def test_failed_write_preserves_existing_hook_and_removes_temporary_file(self):
        hook = self.site / "00-nvbroadcast-google-namespace.pth"
        hook.write_text("# previous complete hook\n")
        before = set(self.site.iterdir())
        with (
            mock.patch.object(installer.os, "fsync", side_effect=OSError("write failed")),
            self.assertRaisesRegex(OSError, "write failed"),
        ):
            self.configure()
        self.assertEqual(hook.read_text(), "# previous complete hook\n")
        self.assertEqual(set(self.site.iterdir()), before)

    def test_system_interpreter_is_not_modified(self):
        with (
            mock.patch.object(installer.sys, "prefix", sys.base_prefix),
            mock.patch.object(installer.sysconfig, "get_path") as paths,
        ):
            installer.prepare_virtualenv_namespaces()
        paths.assert_not_called()

    def test_site_outside_venv_is_rejected(self):
        with (
            mock.patch.object(installer.sys, "prefix", str(self.venv)),
            mock.patch.object(installer.sysconfig, "get_path", return_value=str(self.system_site)),
            self.assertRaises(ValueError),
        ):
            installer.prepare_virtualenv_namespaces()
        self.assertEqual(list(self.system_site.iterdir()), [])


if __name__ == "__main__":
    unittest.main()
